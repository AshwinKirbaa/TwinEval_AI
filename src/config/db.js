const fs = require('fs');
const path = require('path');
const { DatabaseSync } = require('node:sqlite');
const { Pool } = require('pg');
require('dotenv').config();

const isVercel = Boolean(process.env.VERCEL);
const databaseUrl = process.env.DATABASE_URL;

const configuredPath = process.env.DB_PATH || './database/twineval.db';

const databasePath = isVercel
    ? '/tmp/twineval.db'
    : (
        path.isAbsolute(configuredPath)
            ? configuredPath
            : path.resolve(__dirname, '../..', configuredPath)
    );

if (!isVercel) {
    fs.mkdirSync(path.dirname(databasePath), { recursive: true });
}

const db = databaseUrl ? null : new DatabaseSync(databasePath);
if (db) {
    db.exec('PRAGMA foreign_keys = ON;');
    db.exec('PRAGMA journal_mode = WAL;');
    db.exec('PRAGMA busy_timeout = 5000;');
}

class SQLiteConnection {
    async execute(sql, params = []) {
        const normalizedParams = (Array.isArray(params) ? params : []).map(value =>
            typeof value === 'boolean' ? (value ? 1 : 0) : value
        );
        const trimmed = sql.trim().toUpperCase();

        // Seed/schema files may contain multiple SQL statements. SQLite's
        // exec() is the correct API for those scripts; model queries use
        // prepare()/run()/all() below.
        if (normalizedParams.length === 0 && sql.includes(';') && !/^SELECT\b|^WITH\b|^PRAGMA\b/.test(trimmed)) {
            db.exec(sql);
            return [{ insertId: 0, affectedRows: 0 }, []];
        }

        const statement = db.prepare(sql);
        if (trimmed.startsWith('SELECT') || trimmed.startsWith('WITH') || trimmed.startsWith('PRAGMA')) {
            return [statement.all(...normalizedParams), []];
        }

        const result = statement.run(...normalizedParams);
        return [{
            insertId: Number(result.lastInsertRowid || 0),
            affectedRows: Number(result.changes || 0)
        }, []];
    }

    async beginTransaction() {
        db.exec('BEGIN');
    }

    async commit() {
        db.exec('COMMIT');
    }

    async rollback() {
        db.exec('ROLLBACK');
    }

    release() {
        // Kept for compatibility with the previous MySQL pool API.
    }
}

const connection = new SQLiteConnection();

const sqlitePool = {
    execute: (...args) => connection.execute(...args),
    getConnection: async () => connection
};

const primaryKeys = {
    users: 'user_id', student: 'student_id', evaluationresult: 'evaluation_id',
    learningplan: 'plan_id', teacheranalytics: 'analytics_id',
    questionpaper: 'paper_id', question: 'question_id', answerkey: 'answer_key_id',
    submission: 'submission_id', questionresult: 'result_id'
};

function postgresSql(sql) {
    let index = 0;
    return sql.replace(/\?/g, () => `$${++index}`);
}

class PostgresConnection {
    constructor(client, ownsClient = false) {
        this.client = client;
        this.ownsClient = ownsClient;
    }

    async execute(sql, params = []) {
        let query = sql.trim().replace(/;$/, '');
        const normalizedParams = (Array.isArray(params) ? params : []).map(value =>
            typeof value === 'boolean' ? (value ? 1 : 0) : value
        );
        const insert = query.match(/^INSERT\s+INTO\s+([A-Za-z_]+)/i);
        let insertedKey = null;
        if (insert && !/\bRETURNING\b/i.test(query)) {
            insertedKey = primaryKeys[insert[1].toLowerCase()];
            if (insertedKey) query += ` RETURNING ${insertedKey}`;
        }
        const result = await this.client.query(postgresSql(query), normalizedParams);
        if (/^SELECT\b|^WITH\b/i.test(query)) return [result.rows, []];
        return [{
            insertId: insertedKey && result.rows[0] ? Number(result.rows[0][insertedKey]) : 0,
            affectedRows: Number(result.rowCount || 0)
        }, []];
    }

    async beginTransaction() { await this.client.query('BEGIN'); }
    async commit() { await this.client.query('COMMIT'); }
    async rollback() { await this.client.query('ROLLBACK'); }
    release() { if (this.ownsClient) this.client.release(); }
}

const pgPool = databaseUrl ? new Pool({
    connectionString: databaseUrl,
    ssl: process.env.NODE_ENV === 'production' ? { rejectUnauthorized: false } : undefined
}) : null;

const pool = pgPool ? {
    execute: (...args) => new PostgresConnection(pgPool).execute(...args),
    getConnection: async () => new PostgresConnection(await pgPool.connect(), true)
} : sqlitePool;

async function initializeDatabase() {
    const schemaPath = path.join(__dirname, '../../docs/sqlite/schema.sql');
    let schema = fs.readFileSync(schemaPath, 'utf8');
    if (pgPool) {
        // The table definitions are intentionally shared. PostgreSQL needs
        // identity columns instead of SQLite AUTOINCREMENT and uses its own
        // timestamp maintenance below.
        schema = schema.split('CREATE TRIGGER IF NOT EXISTS')[0]
            .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
        await pgPool.query(schema);
        await pgPool.query(`
            CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
            BEGIN NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW; END;
            $$ LANGUAGE plpgsql;
            DROP TRIGGER IF EXISTS trg_users_updated_at ON Users;
            CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON Users
              FOR EACH ROW EXECUTE FUNCTION set_updated_at();
            DROP TRIGGER IF EXISTS trg_student_updated_at ON Student;
            CREATE TRIGGER trg_student_updated_at BEFORE UPDATE ON Student
              FOR EACH ROW EXECUTE FUNCTION set_updated_at();
            DROP TRIGGER IF EXISTS trg_question_paper_updated_at ON QuestionPaper;
            CREATE TRIGGER trg_question_paper_updated_at BEFORE UPDATE ON QuestionPaper
              FOR EACH ROW EXECUTE FUNCTION set_updated_at();
        `);
        return;
    }
    db.exec(schema);
    runMigrations();
}

function runMigrations() {
    // Additive, idempotent migrations for databases created before a
    // given schema change -- CREATE TABLE IF NOT EXISTS above only
    // covers brand-new databases, so an existing Users table (from a
    // database created before the profile-photo feature was added)
    // needs an explicit ALTER TABLE. Guarded to run safely on every
    // startup: SQLite has no "ADD COLUMN IF NOT EXISTS", so the
    // existing column set is checked first.
    const userColumns = db.prepare('PRAGMA table_info(Users)').all().map(c => c.name);
    if (!userColumns.includes('avatar_url')) {
        db.exec('ALTER TABLE Users ADD COLUMN avatar_url TEXT');
        console.log('🔧 Migrated database: added Users.avatar_url');
    }
    for (const column of ['college', 'department', 'year']) {
        if (!userColumns.includes(column)) {
            db.exec(`ALTER TABLE Users ADD COLUMN ${column} TEXT`);
            console.log(`🔧 Migrated database: added Users.${column}`);
        }
    }
    for (const column of ['email_verified_at', 'verification_token_hash', 'verification_expires_at']) {
        if (!userColumns.includes(column)) {
            db.exec(`ALTER TABLE Users ADD COLUMN ${column} TEXT`);
            console.log(`🔧 Migrated database: added Users.${column}`);
        }
    }
    if (!userColumns.includes('google_subject')) {
        db.exec('ALTER TABLE Users ADD COLUMN google_subject TEXT');
        console.log('🔧 Migrated database: added Users.google_subject');
    }
    db.exec('CREATE UNIQUE INDEX IF NOT EXISTS idx_user_google_subject ON Users(google_subject)');
    // Accounts created before verification was introduced remain usable.
    db.exec("UPDATE Users SET email_verified_at = COALESCE(email_verified_at, created_at) WHERE email_verified_at IS NULL AND verification_token_hash IS NULL");
}

async function testConnection() {
    try {
        await initializeDatabase();
        if (pgPool) {
            await pgPool.query('SELECT 1');
            console.log('✅ PostgreSQL database ready.');
        } else {
            db.prepare('SELECT 1').get();
            console.log(`✅ SQLite database ready: ${databasePath}`);
        }
        return true;
    } catch (error) {
        console.error('❌ Database initialization failed:', error.message);
        throw error;
    }
}

